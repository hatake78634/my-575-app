create table if not exists public.coin_wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance bigint not null default 0 check (balance >= 0), updated_at timestamptz not null default now()
);
create table if not exists public.coin_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount bigint not null check (amount <> 0), balance_after bigint not null check (balance_after >= 0),
  reason text not null, reference_key text not null, created_at timestamptz not null default now(),
  unique(user_id, reference_key)
);
create table if not exists public.shop_products (
  id text primary key, name text not null, description text not null,
  item_kind text not null check(item_kind in ('theme','frame')), item_id text not null,
  price bigint not null check(price >= 0), is_public boolean not null default true, display_order integer not null default 0,
  unique(item_kind, item_id)
);
create table if not exists public.shop_purchases (
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id text not null references public.shop_products(id), purchased_at timestamptz not null default now(),
  primary key(user_id, product_id)
);
create table if not exists public.login_bonus_claims (
  user_id uuid not null references auth.users(id) on delete cascade,
  claim_date date not null, amount bigint not null check(amount > 0), claimed_at timestamptz not null default now(),
  primary key(user_id, claim_date)
);
create table if not exists public.daily_task_catalog (
  id text primary key, name text not null, description text not null, event_kind text not null,
  target_count integer not null check(target_count > 0), reward bigint not null check(reward > 0), is_public boolean not null default true
);
create table if not exists public.daily_task_claims (
  user_id uuid not null references auth.users(id) on delete cascade,
  task_id text not null references public.daily_task_catalog(id), claim_date date not null,
  claimed_at timestamptz not null default now(), primary key(user_id, task_id, claim_date)
);

