create or replace function public.ensure_my_wallet() returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare v uuid:=auth.uid(); b bigint;
begin if v is null then raise exception 'authentication required'; end if;
 insert into public.coin_wallets(user_id) values(v) on conflict do nothing;
 select balance into b from public.coin_wallets where user_id=v; return b; end $$;

create or replace function public.claim_daily_login_bonus() returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare v uuid:=auth.uid(); d date:=(now() at time zone 'Asia/Tokyo')::date; reward bigint:=30; b bigint;
begin if v is null then raise exception 'authentication required'; end if;
 insert into public.login_bonus_claims(user_id,claim_date,amount) values(v,d,reward) on conflict do nothing;
 if not found then return (select balance from public.coin_wallets where user_id=v); end if;
 insert into public.coin_wallets(user_id,balance) values(v,reward) on conflict(user_id) do update set balance=coin_wallets.balance+reward,updated_at=now() returning balance into b;
 insert into public.coin_ledger(user_id,amount,balance_after,reason,reference_key) values(v,reward,b,'login_bonus','login:'||d); return b; end $$;

create or replace function public.purchase_shop_product(p_product_id text) returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare v uuid:=auth.uid(); p public.shop_products%rowtype; b bigint;
begin if v is null then raise exception 'authentication required'; end if;
 select * into p from public.shop_products where id=p_product_id and is_public for share; if not found then raise exception 'product not found'; end if;
 insert into public.coin_wallets(user_id) values(v) on conflict do nothing; select balance into b from public.coin_wallets where user_id=v for update;
 if exists(select 1 from public.shop_purchases where user_id=v and product_id=p.id) then raise exception 'already purchased'; end if;
 if b<p.price then raise exception 'insufficient balance'; end if; b:=b-p.price;
 update public.coin_wallets set balance=b,updated_at=now() where user_id=v;
 insert into public.shop_purchases(user_id,product_id) values(v,p.id);
 if p.item_kind='theme' then insert into public.user_themes(user_id,theme_id) values(v,p.item_id) on conflict do nothing;
 else insert into public.user_avatar_frames(user_id,frame_id) values(v,p.item_id) on conflict do nothing; end if;
 insert into public.coin_ledger(user_id,amount,balance_after,reason,reference_key) values(v,-p.price,b,'shop_purchase','purchase:'||p.id); return b; end $$;

create or replace function public.claim_daily_task(p_task_id text) returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare v uuid:=auth.uid(); d date:=(now() at time zone 'Asia/Tokyo')::date; start_at timestamptz; finish_at timestamptz; t public.daily_task_catalog%rowtype; progress bigint; b bigint;
begin if v is null then raise exception 'authentication required'; end if;
 start_at:=(d::timestamp at time zone 'Asia/Tokyo'); finish_at:=start_at+interval '1 day';
 select * into t from public.daily_task_catalog where id=p_task_id and is_public; if not found then raise exception 'task not found'; end if;
 progress:=case t.event_kind
  when 'haiku' then (select count(*) from public.haikus_2 where user_id=v and created_at>=start_at and created_at<finish_at)
  when 'like' then (select count(*) from public.likes_2 where user_id=v and created_at>=start_at and created_at<finish_at)
  when 'utaawase' then (select count(*) from public.utaawase_members where user_id=v and joined_at>=start_at and joined_at<finish_at)
  else 0 end;
 if progress<t.target_count then raise exception 'task is not complete'; end if;
 insert into public.daily_task_claims(user_id,task_id,claim_date) values(v,t.id,d) on conflict do nothing; if not found then raise exception 'reward already claimed'; end if;
 insert into public.coin_wallets(user_id,balance) values(v,t.reward) on conflict(user_id) do update set balance=coin_wallets.balance+t.reward,updated_at=now() returning balance into b;
 insert into public.coin_ledger(user_id,amount,balance_after,reason,reference_key) values(v,t.reward,b,'daily_task','task:'||t.id||':'||d); return b; end $$;

revoke all on function public.ensure_my_wallet(), public.claim_daily_login_bonus(), public.purchase_shop_product(text), public.claim_daily_task(text) from public,anon;
grant execute on function public.ensure_my_wallet(), public.claim_daily_login_bonus(), public.purchase_shop_product(text), public.claim_daily_task(text) to authenticated;
